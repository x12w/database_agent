def exec_sql(sql, params=None):
    """Execute SQL and print result."""
    try:
        if params:
            cur.execute(sql, params)
        else:
            cur.execute(sql)
        conn.commit()
        return True
    except Exception as e:
        print(f"  FAIL: {str(e)[:100]}")
        conn.rollback()
        return False

def insert_many(sql, rows):
    """Insert multiple rows."""
    try:
        cur.executemany(sql, rows)
        conn.commit()
        return len(rows)
    except Exception as e:
        print(f"  FAIL: {str(e)[:100]}")
        conn.rollback()
        return 0

